"""Apply deterministic, reviewable repairs to the best Freerouting candidate.

This is intentionally a candidate-repair tool, not a release bypass.  Every
output must still pass KiCad DRC with schematic parity and manufacturing gates.
Coordinates are millimetres and are tied to the Rev C placement generated by
``scripts/build_board.py``.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pcbnew


def point(x: float, y: float) -> pcbnew.VECTOR2I:
    return pcbnew.VECTOR2I_MM(x, y)


def add_track(
    board: pcbnew.BOARD,
    net_name: str,
    start: tuple[float, float],
    end: tuple[float, float],
    width_mm: float,
    layer: int,
) -> None:
    track = pcbnew.PCB_TRACK(board)
    track.SetNet(board.FindNet(net_name))
    track.SetStart(point(*start))
    track.SetEnd(point(*end))
    track.SetWidth(pcbnew.FromMM(width_mm))
    track.SetLayer(layer)
    board.Add(track)


def add_path(
    board: pcbnew.BOARD,
    net_name: str,
    vertices: list[tuple[float, float]],
    width_mm: float,
    layer: int,
) -> None:
    for start, end in zip(vertices, vertices[1:]):
        add_track(board, net_name, start, end, width_mm, layer)


def add_via(
    board: pcbnew.BOARD,
    net_name: str,
    at: tuple[float, float],
    diameter_mm: float = 0.6,
    drill_mm: float = 0.3,
) -> None:
    via = pcbnew.PCB_VIA(board)
    via.SetNet(board.FindNet(net_name))
    via.SetPosition(point(*at))
    via.SetWidth(pcbnew.FromMM(diameter_mm))
    via.SetDrill(pcbnew.FromMM(drill_mm))
    via.SetLayerPair(pcbnew.F_Cu, pcbnew.B_Cu)
    board.Add(via)


def near(a: pcbnew.VECTOR2I, xy: tuple[float, float], tolerance_mm: float = 0.002) -> bool:
    return (
        abs(pcbnew.ToMM(a.x) - xy[0]) <= tolerance_mm
        and abs(pcbnew.ToMM(a.y) - xy[1]) <= tolerance_mm
    )


def remove_track(
    board: pcbnew.BOARD,
    track_pool: list,
    net_name: str,
    start: tuple[float, float],
    end: tuple[float, float],
) -> None:
    matches = [
        (index, item)
        for index, item in enumerate(track_pool)
        if item.GetClass() != "PCB_VIA"
        and item.GetNetname() == net_name
        and (
            (near(item.GetStart(), start) and near(item.GetEnd(), end))
            or (near(item.GetStart(), end) and near(item.GetEnd(), start))
        )
    ]
    if len(matches) != 1:
        raise RuntimeError(
            f"Expected one {net_name} track {start}->{end}; found {len(matches)}"
        )
    index, item = matches[0]
    board.Remove(item)
    del track_pool[index]


def remove_tracks(
    board: pcbnew.BOARD,
    track_pool: list,
    net_name: str,
    start: tuple[float, float],
    end: tuple[float, float],
    expected: int,
) -> None:
    matches = [
        (index, item)
        for index, item in enumerate(track_pool)
        if item.GetClass() != "PCB_VIA"
        and item.GetNetname() == net_name
        and (
            (near(item.GetStart(), start) and near(item.GetEnd(), end))
            or (near(item.GetStart(), end) and near(item.GetEnd(), start))
        )
    ]
    if len(matches) != expected:
        raise RuntimeError(
            f"Expected {expected} {net_name} tracks {start}->{end}; "
            f"found {len(matches)}"
        )
    for index, item in reversed(matches):
        board.Remove(item)
        del track_pool[index]


def select_tracks(
    track_pool: list,
    net_name: str,
    start: tuple[float, float],
    end: tuple[float, float],
    expected: int,
) -> list:
    matches = [
        item
        for item in track_pool
        if item.GetClass() != "PCB_VIA"
        and item.GetNetname() == net_name
        and (
            (near(item.GetStart(), start) and near(item.GetEnd(), end))
            or (near(item.GetStart(), end) and near(item.GetEnd(), start))
        )
    ]
    if len(matches) != expected:
        raise RuntimeError(
            f"Expected {expected} {net_name} tracks {start}->{end}; "
            f"found {len(matches)}"
        )
    return matches


def replace_right_vbat_zone(board: pcbnew.BOARD) -> None:
    """Widen the GND corridor beside C3-C6 on the bottom layer."""
    candidates = []
    for zone in board.Zones():
        box = zone.GetBoundingBox()
        if (
            zone.GetNetname() == "VBAT"
            and zone.GetLayer() == pcbnew.B_Cu
            and abs(pcbnew.ToMM(box.GetLeft()) - 50.5) < 0.1
            and abs(pcbnew.ToMM(box.GetRight()) - 63.0) < 0.1
        ):
            candidates.append(zone)
    if len(candidates) != 1:
        raise RuntimeError(f"Expected one right-side B.Cu VBAT zone; found {len(candidates)}")
    zone = candidates[0]
    zone.Outline().RemoveAllContours()
    zone.Outline().NewOutline()
    for x, y in [
        (56.5, 15.0),
        (63.0, 15.0),
        (63.0, 50.0),
        (56.5, 50.0),
        (56.5, 42.0),
        (50.5, 42.0),
        (50.5, 28.5),
        (53.0, 28.5),
        (53.0, 23.0),
        (56.5, 23.0),
    ]:
        zone.Outline().Append(pcbnew.FromMM(x), pcbnew.FromMM(y))


def repair(board: pcbnew.BOARD) -> None:
    # Perform footprint/zone geometry edits before deleting any tracks; KiCad
    # 10's SWIG wrapper can invalidate later collection iteration after a
    # BOARD::Remove call even though the saved board remains valid.
    track_pool = list(board.GetTracks())
    r14 = next((fp for fp in board.GetFootprints() if fp.GetReference() == "R14"), None)
    th1 = next((fp for fp in board.GetFootprints() if fp.GetReference() == "TH1"), None)
    if r14 is None:
        raise RuntimeError("R14 footprint not found")
    if th1 is None:
        raise RuntimeError("TH1 footprint not found")
    print("repair: VBAT clearance", flush=True)
    # Select every deletion before changing board geometry.  KiCad 10's SWIG
    # iterators are invalidated by BOARD::Remove and footprint moves.
    tracks_to_remove = []
    tracks_to_remove += select_tracks(
        track_pool, "VBAT", (18.2381, 9.9182), (16.3654, 9.9182), expected=1
    )
    tracks_to_remove += select_tracks(
        track_pool, "VDRV", (17.4, 23.0), (17.4, 21.825), expected=1
    )
    tracks_to_remove += select_tracks(
        track_pool, "G_Q1", (16.5, 26.25), (19.8, 26.25), expected=2
    )
    tracks_to_remove += select_tracks(
        track_pool, "G_Q1", (16.5, 29.0), (16.5, 26.25), expected=1
    )
    tracks_to_remove += select_tracks(
        track_pool, "NTC", (17.675, 12.5), (15.6808, 12.5), expected=1
    )
    tracks_to_remove += select_tracks(
        track_pool, "NTC", (15.6808, 12.5), (13.5409, 14.6399), expected=1
    )
    tracks_to_remove += select_tracks(
        track_pool, "+5V", (25.0, 46.7483), (31.9237, 39.8246), expected=1
    )
    print("repair: move R14 position", flush=True)
    r14.SetPosition(point(17.4, 25.0))
    print("repair: move R14 orientation", flush=True)
    r14.SetOrientationDegrees(270.0)
    print("repair: move TH1", flush=True)
    th1.SetPosition(point(12.5, 13.0))
    th1.SetOrientationDegrees(180.0)
    for item in tracks_to_remove:
        board.Remove(item)

    # Move the short VBAT segment away from the SW via at (17, 9).
    add_path(
        board,
        "VBAT",
        [(18.2381, 9.9182), (18.05, 10.25), (16.55, 10.25), (16.3654, 9.9182)],
        0.5,
        pcbnew.F_Cu,
    )

    # Complete D4.2 to VBAT on B.Cu.  The endpoint via starts on accepted VBAT
    # copper, avoiding R1.2/VSNS on the front; the route stays left of SW.
    print("repair: VBAT D4", flush=True)
    add_via(board, "VBAT", (14.1027, 9.5723))
    add_path(
        board,
        "VBAT",
        [(14.1027, 9.5723), (14.0, 12.5), (15.4, 15.5)],
        0.5,
        pcbnew.B_Cu,
    )
    add_via(board, "VBAT", (15.4, 15.5))
    add_path(board, "VBAT", [(15.4, 15.5), (15.5, 15.5)], 0.5, pcbnew.F_Cu)

    # Move R14 below the regulator pocket so VFB no longer has to cross the
    # VDRV perimeter.  Re-route Q1's gate from the south to preserve clearance.
    print("repair: VFB", flush=True)
    print("repair: replace R14 VDRV", flush=True)
    add_path(board, "VDRV", [(17.4, 23.0), (17.4, 24.175)], 0.5, pcbnew.F_Cu)
    print("repair: replace Q1 gate", flush=True)
    add_path(
        board,
        "G_Q1",
        [(17.8875, 29.0), (16.5, 29.0), (16.5, 27.0), (19.8, 27.0), (19.8, 26.25)],
        0.8,
        pcbnew.F_Cu,
    )
    add_path(
        board,
        "VFB",
        [(11.35, 20.175), (10.2, 20.175), (10.2, 24.0), (12.3, 24.0), (12.3, 24.825)],
        0.3,
        pcbnew.F_Cu,
    )
    add_path(
        board,
        "VFB",
        [(12.3, 24.825), (12.3, 25.5), (17.4, 25.5), (17.4, 25.825)],
        0.3,
        pcbnew.F_Cu,
    )

    # Connect C9 directly to D4.1 above the TRIG/NTC barrier endpoints.  Vias
    # sit outside both SMD pads to avoid an unfilled via-in-pad process.
    print("repair: VREG_IN", flush=True)
    add_path(board, "VREG_IN", [(8.5, 21.275), (6.4, 21.275)], 0.4, pcbnew.F_Cu)
    add_via(board, "VREG_IN", (6.4, 21.275), diameter_mm=0.6, drill_mm=0.3)
    add_path(
        board,
        "VREG_IN",
        [(6.4, 21.275), (6.4, 12.2), (11.5, 12.2), (11.5, 14.0)],
        0.4,
        pcbnew.B_Cu,
    )
    add_via(board, "VREG_IN", (11.5, 14.0), diameter_mm=0.6, drill_mm=0.3)
    add_path(board, "VREG_IN", [(11.5, 14.0), (11.5, 15.5)], 0.4, pcbnew.F_Cu)

    # Complete the current-amplifier test-point branch on B.Cu.
    print("repair: CUR", flush=True)
    add_via(board, "CUR", (35.8691, 41.05))
    add_path(board, "CUR", [(35.8691, 41.05), (44.0, 42.0)], 0.3, pcbnew.B_Cu)
    add_via(board, "CUR", (44.0, 42.0))

    # Stitch each front GND pocket at a reviewed location.  C18.2 escapes past
    # the end of its narrow front-layer corridor before dropping to B.Cu.
    print("repair: GND vias", flush=True)
    for via_xy in [
        (34.8505, 41.9913),
        (20.5622, 37.8155),
        (54.8787, 38.8550),
        (14.0955, 34.6071),
        (3.5134, 37.3239),
        (55.0050, 33.2550),
        (55.0050, 29.2550),
        (9.3000, 5.1000),
    ]:
        add_via(board, "GND", via_xy, diameter_mm=0.8, drill_mm=0.4)
    add_via(board, "GND", (29.275, 42.0), diameter_mm=0.8, drill_mm=0.4)
    add_path(
        board,
        "GND",
        [(8.775, 31.5), (8.775, 30.65), (5.5, 30.65), (5.5, 31.025)],
        0.3,
        pcbnew.F_Cu,
    )
    # Stitch the C12/C16 front-zone pocket at open copper outside the 0603
    # solder pads.  Zone fill makes the connection without a dangling track.
    add_via(board, "GND", (5.5, 34.0), diameter_mm=0.6, drill_mm=0.3)
    add_via(board, "GND", (12.3, 23.175), diameter_mm=0.8, drill_mm=0.4)
    add_via(board, "GND", (70.0, 55.0), diameter_mm=1.0, drill_mm=0.5)
    add_path(board, "GND", [(11.675, 13.0), (12.4, 13.0)], 0.3, pcbnew.F_Cu)
    add_via(board, "GND", (12.4, 13.0), diameter_mm=0.6, drill_mm=0.3)
    add_path(
        board,
        "GND",
        [(54.975, 30.0), (54.975, 34.0), (54.975, 38.0), (54.275, 40.5), (54.275, 44.5), (45.0, 44.5)],
        1.0,
        pcbnew.F_Cu,
    )

    # Reconnect the thermistor after moving it out of the SW copper pocket.
    add_path(
        board,
        "NTC",
        [(13.325, 13.0), (13.5409, 14.6399)],
        0.3,
        pcbnew.F_Cu,
    )

    # Move the +5 V bottom-layer trunk around C18.2, allowing a pad-centred
    # GND via without shrinking the standard 0.3 mm drill.
    add_path(
        board,
        "+5V",
        [(25.0, 46.7483), (32.5, 46.7483), (32.5, 39.8246), (31.9237, 39.8246)],
        0.3,
        pcbnew.B_Cu,
    )

    # The new VBAT/VREG corridors divide the front SW pour into three useful
    # regions; stitch the two regions that no longer contain the original via.
    add_via(board, "SW", (20.0, 10.5), diameter_mm=1.0, drill_mm=0.5)
    replace_right_vbat_zone(board)

    # KiCad 10's standalone Python wrapper can crash while refilling imported
    # Freerouting geometry.  Save the edits and let the current KiCad CLI DRC
    # perform the authoritative connectivity check against existing fills.
    print("repair: complete", flush=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    board = pcbnew.LoadBoard(str(args.input.resolve()))
    repair(board)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    print("saving", flush=True)
    pcbnew.SaveBoard(str(args.output.resolve()), board)
    print("saved", flush=True)


if __name__ == "__main__":
    main()
